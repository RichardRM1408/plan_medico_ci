    TRIM(ESTADO_SESION) = 'Realizada'
    AND DATE(SAFE.PARSE_DATETIME('%d/%m/%Y %H:%M:%S', TRIM(FECHA_HORA_INICIO))) =
        SAFE.PARSE_DATE('%d/%m/%Y', TRIM(FECHA_PREVISTA)),
    CAST(PRES_SESION_CAB_PK AS STRING), NULL
  ) AS NUM_KEY,

