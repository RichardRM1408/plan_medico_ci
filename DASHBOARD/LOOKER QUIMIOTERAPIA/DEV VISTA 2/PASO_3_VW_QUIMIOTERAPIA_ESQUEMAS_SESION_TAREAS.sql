  SAFE.PARSE_DATE('%d/%m/%Y', TRIM(FECHA_INICIO_PROTOCOLO))                                   AS FECHA_INICIO_PROTOCOLO_DT,
  -- SESION
  SAFE.PARSE_DATE('%d/%m/%Y', TRIM(FECHA_PREVISTA))                                           AS FECHA_PREVISTA_DT,
  -- TAREA
  SAFE.PARSE_DATE('%d/%m/%Y', TRIM(FECHA_HORA_INICIO))                                        AS FECHA_HORA_INICIO_DT,

  -- KEY (CONTEO POR EL CUAL SE VA RALIZAR EL COUNT DISTINC - DEPENDE DEL KPI)

  CAST(HOJA_PROT_PK AS STRING) AS KEY,
  CAST(NULL AS STRING)         AS NUM_KEY,                            -- no aplica para este KPI


  -- COLUMNAS ADICIONALES DE INTERES
  -- PROTOCOLO
  CAST(HOJA_PROT_PK AS STRING)         AS HOJA_PROT_PK,
  TRIM(DIAGNOSTICO)                    AS DIAGNOSTICO_PROTOCOLO,
  TRIM(CAST(CODIGO_CLIENTE AS STRING)) AS CODIGO_CLIENTE_PROTOCOLO,
  TRIM(NOMBRE_ESQUEMA_TERAPEUTICO)     AS NOMBRE_ESQUEMA_TERAPEUTICO,
  TRIM(ESTADO_PROTOCOLO)               AS ESTADO_PROTOCOLO,
  -- CICLO - SESION
  CAST(PRES_SESION_CAB_PK AS STRING)   AS PRES_SESION_CAB_PK,
  TRIM(ESTADO_SESION)                  AS ESTADO_SESION,
  TRIM(TIEMPO_ESTIMADO)                AS TIEMPO_ESTIMADO,
  CASE
  WHEN REGEXP_EXTRACT(TIEMPO_ESTIMADO, r'(\d+)') IS NULL THEN NULL
  WHEN SAFE_CAST(REGEXP_EXTRACT(TIEMPO_ESTIMADO, r'(\d+)') AS INT64) < 240 THEN 'CORTA (<4h)'  
  WHEN SAFE_CAST(REGEXP_EXTRACT(TIEMPO_ESTIMADO, r'(\d+)') AS INT64) BETWEEN 240 AND 360 THEN 'MEDIANA (4-6h)'
  WHEN SAFE_CAST(REGEXP_EXTRACT(TIEMPO_ESTIMADO, r'(\d+)') AS INT64) > 360 THEN 'LARGA (>6h)'
  END                                  AS CLASIFICACION_DURACION_QUIMIOTERAPIA,
  -- TAREA
  TRIM(ESTADO_TAREA)                   AS ESTADO_TAREA,
  
  ------------------------
  -- CAMPOS CALCULADOS ADICIONALES - PEDIDO JAVIE 09/09/2023
  -- 1) Min → horas decimales
  ROUND(CAST(SAFE_CAST(REGEXP_EXTRACT(TRIM(TIEMPO_ESTIMADO), '([0-9]+)') AS INT64) AS NUMERIC) / 60,1) AS TIEMPO_ESTIMADO_EN_HORAS,


  -- 2) Flag > 18 horas
  CASE WHEN SAFE_CAST(REGEXP_EXTRACT(TIEMPO_ESTIMADO, r'([0-9]+)') AS INT64) > 18*60
       THEN 1 ELSE 0 END
    AS TIEMPO_ESTIMADO_MAYOR_18_HORAS,

  ------------------------

  /* ===== FILTROS PRESTACIONALES / DIMENSIONES ===== */
  NUM_ENCUENTRO,
  COD_PACIENTE,
  NOM_PACIENTE,
  SEXO,
  NOM_APELL_PATERNO_PCTE,
  NOM_APELL_MATERNO_PCTE,
  NOM_COMPLETO,
  FECHA_ATENCION,
  COD_GRUPO_ESPECIALIDAD,
  DES_GRUPO_ESPECIALIDAD,
  COD_SERVICIO,
  DES_SERVICIO,
  COD_TIPO_CITA,
  DES_TIPO_CITA,
  COD_ORIGEN_ATENCION,
  DES_ORIGEN_ATENCION,
  COD_MOTIVO_ING_ENC,
  DES_MOTIVO_ING_ENC,
  COD_UNIDAD_NEGOCIO,
  DES_UNIDAD_NEGOCIO,
  AMBITO_HOMOLOGADO,
  COD_DIAGNOSTICO_01,
  DES_DIAGNOSTICO_01,
  COD_DIAGNOSTICO_02,
  DES_DIAGNOSTICO_02,
  COD_DIAGNOSTICO_03,
  DES_DIAGNOSTICO_03,
  COD_MEDICO,
  NOM_MEDICO,
  NOM_SEDE,
  LOCALIZACION_ANATOMICA, -- Agregado 15/09/2025 a pedido de Irpiri
  EDAD_HOMOLOGADA,
  RANGO_ETARIO,
  RANGO_ETARIO_10_ANIOS,
  FH_ULTIMA_ACTUALIZACION
FROM `ci-datalake-dev.ci_dtlk_bqd_access_dev.TBL_ONCO_PROTOCOLO_PREFACTURA`
WHERE 
  TRIM(ESTADO_PROTOCOLO)  = 'Planificado'

  -- COMENTADO: AND TRIM(AMBITO_HOMOLOGADO)  = 'Ambulatorio' 
  -- En el Diccionario aparece “Ambulatorio”.  
  -- Irpiri indica que no debe hacerse esta distinción,  
  -- es decir, debe considerarse como “Ambulatorio + Hospitalario”.

  --AND TRIM(AMBITO_HOMOLOGADO) = 'Ambulatorio'
  
  AND HOJA_PROT_PK IS NOT NULL
  AND SAFE.PARSE_DATE('%d/%m/%Y', TRIM(FECHA_INICIO_PROTOCOLO)) IS NOT NULL

UNION ALL

