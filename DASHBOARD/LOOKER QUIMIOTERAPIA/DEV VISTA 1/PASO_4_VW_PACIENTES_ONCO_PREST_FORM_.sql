    COD_TIPO_CITA,
    DES_TIPO_CITA,
    COD_ORIGEN_ATENCION,
    DES_ORIGEN_ATENCION,
    COD_MOTIVO_ING_ENC,
    DES_MOTIVO_ING_ENC,
    COD_UNIDAD_NEGOCIO,
    DES_UNIDAD_NEGOCIO,
    COD_DIAGNOSTICO_01,
    DES_DIAGNOSTICO_01,
    COD_DIAGNOSTICO_02,
    DES_DIAGNOSTICO_02,
    COD_DIAGNOSTICO_03,
