   FECHA_ACTUAL_TS,
   HORA_INICIO_QUIMIOTERAPIA_HOMOLOGADO, -- agregado 2/09/2025
   HORA_TERMINO_QUIMIOTERAPIA_HOMOLOGADO, -- agregado 2/09/2025
   DURACION_QUIMIOTERAPIA, -- agregado 2/09/2025
    CLASIFICACION_DURACION_QUIMIOTERAPIA, -- agregado 3/09/2025

   EDAD_HOMOLOGADA,
