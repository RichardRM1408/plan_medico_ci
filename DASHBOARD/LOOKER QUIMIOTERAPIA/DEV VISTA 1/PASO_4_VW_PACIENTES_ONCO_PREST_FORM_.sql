    NOM_APELL_MATERNO_PCTE,
    NOM_COMPLETO,
    FECHA_ATENCION,
    COD_GRUPO_ESPECIALIDAD,
    DES_GRUPO_ESPECIALIDAD,
    -- COD_GRUPO_ESPECIALIDAD_ONCO,
    -- DES_GRUPO_ESPECIALIDAD_ONCO,
    COD_SERVICIO,
    DES_SERVICIO,
    -- COD_SERVICIO_ONCO,
