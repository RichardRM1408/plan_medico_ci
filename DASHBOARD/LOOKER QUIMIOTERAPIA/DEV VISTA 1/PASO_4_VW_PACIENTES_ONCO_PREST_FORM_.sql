    TIPO_PACIENTE_HOMOLOGADO,
    AMBITO_HOMOLOGADO,
    FH_ULTIMA_ACTUALIZACION,
    -- PARA AGRUPACION POR AÑO Y MES
    EXTRACT(YEAR  FROM FECHA_ACTUAL_TS)  AS anio_utc,
    EXTRACT(MONTH FROM FECHA_ACTUAL_TS) AS mes_utc,

    -- NORMALIZACION DE DIAGNOSTICO
    REGEXP_REPLACE(UPPER(TRIM(DIAGNOSTICO_ESQUEMA_QUIMIOTERAPIA)), r'\s+', ' ') AS dx_norm,

    -- PRIORIDAD DE CATEGORIAS PARA TIPO PACIENTE
    CASE
      WHEN UPPER(TRIM(TIPO_PACIENTE_HOMOLOGADO)) = 'NUEVO' THEN 1
      WHEN UPPER(TRIM(TIPO_PACIENTE_HOMOLOGADO)) = 'CONTINUADOR' THEN 2
      WHEN UPPER(TRIM(TIPO_PACIENTE_HOMOLOGADO)) = 'USUARIO SIN TIPO PACIENTE' THEN 3
      ELSE 4
    END AS tipo_rank,

    -- FLAG DE NUEVO Y CONTINUADOR (válidos) POR ENCIAM DE NULL
    CASE
      WHEN UPPER(TRIM(TIPO_PACIENTE_HOMOLOGADO)) IN ('NUEVO','CONTINUADOR') THEN 0  -- válidos
      ELSE 1  -- null
    END AS es_sin_tipo_o_otro
  FROM `ci-datalake-dev.ci_dtlk_bqd_business_dev.PACIENTES_ONCOLOGIA_PREST_FORM_QUIMIOTERAPIA_HOMOLOGADO`
  WHERE
    FECHA_ACTUAL_TS >= TIMESTAMP("2025-05-01 00:00:00 UTC") -- mayores a abril , alcance 20/08/2025 Irpiri
    AND NULLIF(TRIM(DIAGNOSTICO_ESQUEMA_QUIMIOTERAPIA), '') IS NOT NULL
),
ranked AS (
  SELECT
    s.*,
    ROW_NUMBER() OVER (
      PARTITION BY
        s.COD_PACIENTE,
        s.anio_utc,
        s.mes_utc,
        s.dx_norm
      ORDER BY
        s.es_sin_tipo_o_otro ASC,  -- 1) primero tipos válidos (Nuevo/Continuador), luego Sin tipo (null)
        s.FECHA_ACTUAL_TS   ASC,   -- 2) dentro de ese grupo, la fecha más antigua
        s.tipo_rank         ASC    -- 3) si misma fecha/hora: Nuevo > Continuador > Sin tipo > otros
    ) AS rn
  FROM src s
)
