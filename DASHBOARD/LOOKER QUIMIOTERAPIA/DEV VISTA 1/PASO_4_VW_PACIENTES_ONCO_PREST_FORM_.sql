    --- COLUMNAS DE FORMULARIO DE QUIMIOTERAPIA HOMOLOGADOS
    FECHA_ATENCION_TS,
    FECHA_ACTUAL_TS,
    HORA_INICIO_QUIMIOTERAPIA_HOMOLOGADO, -- agregado 2/09/2025
